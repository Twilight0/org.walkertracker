class Translator:
    def __init__(self, locale="en"):
        # Normalize locale (e.g. en-US -> en)
        lang = locale.split("-")[0].lower()
        self.locale = lang if lang in TRANSLATIONS else "en"
        self.map = TRANSLATIONS[self.locale]

    def get(self, key, **kwargs):
        text = self.map.get(key, TRANSLATIONS["en"].get(key, key))
        if kwargs:
            return text.format(**kwargs)
        return text
